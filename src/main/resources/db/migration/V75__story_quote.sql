-- V75 — 여백 글의 인용문(story.quote).
--
-- 글이 「책에서 옮긴 문장 + 그에 다는 주석」 두 층이 된다. 인용은 **선택**이라 nullable이고, 기존 행은
-- 전부 NULL로 남아 예전과 똑같이 그려진다(순수 추가 — 백필 없음).
--
-- 200자인 이유: 주석(text 500)보다 짧아야 한다. 화면의 시각 위계(인용은 작게·주석이 본문)와 같은 규칙이고,
-- 정당한 인용의 요건(내 글이 主·인용이 從)과도 같은 방향이다. 공백뿐인 값은 앱이 NULL로 떨어뜨린다
-- (Story.of) — 빈 문자열이 남으면 화면에 글 없는 인용선이 그려지므로, 「인용 없음」의 표현은 NULL 하나뿐이다.
--
-- 쪽수 컬럼은 두지 않는다: ebook은 글자 크기·기기마다 쪽이 달라 적어도 읽는 사람이 못 찾는 숫자다.
--
-- 인덱스 없음 — 인용은 카드에 실려 오는 표시용 값이고, 검색·정렬 축이 아니다.

alter table story add column quote varchar(200) null;
