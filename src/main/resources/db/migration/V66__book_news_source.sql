-- V66 — 책 뉴스에 매체명(출처) 추가.
--
-- 수집원을 네이버 검색 API → 구글 뉴스 RSS로 바꾸면서 생겼다. 구글 RSS는 출처를 <source> 엘리먼트로
-- 구조화해 주므로(제목 접미사를 파싱할 필요가 없다) 그대로 저장해 미니앱이 "제목 · 출처"로 보여준다.
--
-- nullable 인 이유: 출처는 응답에 없을 수도 있는 선택 정보고, 없다고 기사 줄을 버릴 이유가 없다
-- (미니앱은 null이면 라벨을 생략한다). 기존 행도 null로 남았다가 다음 새벽 수집에서 통째로 교체된다.

alter table book_news add column source varchar(100) null;
