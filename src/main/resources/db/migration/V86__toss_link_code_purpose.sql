-- V86 — toss_link_code에 목적(purpose)을 붙여 두 방향의 코드를 가른다.
--
-- 지금까지 이 테이블의 코드는 한 방향뿐이었다: 웹에 로그인한 사람이 발급 → 미니앱에 입력 → 그 계정에
-- 토스 신원이 붙는다(LINK_TOSS). 반대 방향(토스에서 시작한 계정이 PC 웹에 로그인하는 길)이 생기면서
-- 같은 저장소에 두 종류의 코드가 산다.
--
-- 왜 컬럼인가 — 구분이 없으면 <b>웹→토스 연결 코드를 웹 로그인 폼에 먹여 그 계정 세션을 열 수 있다</b>.
-- 어깨너머·스크린샷으로 코드를 본 사람이 얻는 힘이 "내 토스 신원을 붙임"에서 "즉시 웹 로그인"으로 넓어진다.
-- 「발급 조건이 상호 배타라 지금은 user.toss_user_key로 판별된다」는 추론에 기대지 않는 이유는, 그 추론이
-- 나중에 발급 조건을 완화하면 조용히 <b>통과 쪽으로</b> 고장 나기 때문이다. 소비 지점이 자기 목적만 받는다.
-- 선례: email_token의 type 컬럼(검증·재설정·수신거부를 한 테이블에서 타입으로 가른다).
--
-- 기존 행은 전부 웹→토스용이었으므로 기본값이 곧 진실이다(발급 경로가 하나뿐이었다). 어차피 TTL이 5분이라
-- 배포 시점에 살아 있는 미사용 행은 실질 0이다. varchar(16)·not null·default는 MySQL·H2 동일 구문.

alter table toss_link_code add column purpose varchar(16) not null default 'LINK_TOSS';
